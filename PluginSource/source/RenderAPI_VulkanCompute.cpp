// ─── Helper: find suitable memory type ──────────────────────────────────────

static int FindMemoryType(VkPhysicalDevice physDevice, uint32_t typeFilter, VkMemoryPropertyFlags props)
{
    VkPhysicalDeviceMemoryProperties memProps;
    vkGetPhysicalDeviceMemoryProperties(physDevice, &memProps);

    for (uint32_t i = 0; i < memProps.memoryTypeCount; i++)
    {
        if ((typeFilter & (1 << i)) && (memProps.memoryTypes[i].propertyFlags & props) == props)
            return (int)i;
    }
    return -1;
}

// ─── Helper: create a buffer with memory ────────────────────────────────────

struct ComputeBuffer
{
    VkBuffer buffer = VK_NULL_HANDLE;
    VkDeviceMemory memory = VK_NULL_HANDLE;
    VkDeviceSize size = 0;
    void *mapped = nullptr;
};

static bool CreateComputeBuffer(VkDevice device, VkPhysicalDevice physDevice,
                                VkDeviceSize size, VkBufferUsageFlags usage,
                                VkMemoryPropertyFlags memProps, ComputeBuffer &out)
{
    out = {};
    out.size = size;

    VkBufferCreateInfo bufInfo = {};
    bufInfo.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
    bufInfo.size = size;
    bufInfo.usage = usage;
    bufInfo.sharingMode = VK_SHARING_MODE_EXCLUSIVE;

    if (vkCreateBuffer(device, &bufInfo, nullptr, &out.buffer) != VK_SUCCESS)
        return false;

    VkMemoryRequirements memReqs;
    vkGetBufferMemoryRequirements(device, out.buffer, &memReqs);

    int memTypeIdx = FindMemoryType(physDevice, memReqs.memoryTypeBits, memProps);
    if (memTypeIdx < 0)
        return false;

    VkMemoryAllocateInfo allocInfo = {};
    allocInfo.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
    allocInfo.allocationSize = memReqs.size;
    allocInfo.memoryTypeIndex = (uint32_t)memTypeIdx;

    if (vkAllocateMemory(device, &allocInfo, nullptr, &out.memory) != VK_SUCCESS)
        return false;

    if (vkBindBufferMemory(device, out.buffer, out.memory, 0) != VK_SUCCESS)
        return false;

    // Persistently map if host-visible
    if (memProps & VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT)
        vkMapMemory(device, out.memory, 0, size, 0, &out.mapped);

    return true;
}

static void DestroyComputeBuffer(VkDevice device, ComputeBuffer &buf)
{
    if (buf.mapped)
    {
        vkUnmapMemory(device, buf.memory);
        buf.mapped = nullptr;
    }
    if (buf.buffer)
    {
        vkDestroyBuffer(device, buf.buffer, nullptr);
        buf.buffer = VK_NULL_HANDLE;
    }
    if (buf.memory)
    {
        vkFreeMemory(device, buf.memory, nullptr);
        buf.memory = VK_NULL_HANDLE;
    }
}

