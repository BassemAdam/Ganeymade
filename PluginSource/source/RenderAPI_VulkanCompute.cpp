struct SimParams
{
    float dt;              // timestep
    uint32_t particleCount; // number of active particles
    float restDensity;     // target density (e.g., 1000 for water)
    float gasStiffness;    // pressure constant
    float viscosity;       // viscosity coefficient
    float smoothingRadius; // SPH kernel radius h
    float _pad0;           // padding for std140 float3 alignment
    float _pad1;           // padding for std140 float3 alignment
    float gravity[3];         // gravity acceleration vector
    float particleMass;    // mass per particle
    float boundsMin[3];    // container min corner
    float poly6Const;      // precomputed Poly6 kernel constant
    float boundsMax[3];    // container max corner
    float spikyGradConst;  // precomputed Spiky gradient constant
    uint32_t gridDims[3];  // cells per axis
    float viscLapConst;    // precomputed viscosity Laplacian constant
    float gridOrigin[3];   // world-space origin of grid
    uint32_t maxCells;     // gridDims.x * gridDims.y * gridDims.z
    float damping;         // per-frame velocity damping (e.g. 0.998)
    uint32_t bitonicK;    // bitonic sort stage (power of 2)
    uint32_t bitonicJ;    // bitonic sort step  (power of 2)
    float interactionStrength; // >0 attract, <0 repulse, 0 off
    float interactionPos[3];   // world-space interaction point
    float interactionRadius;   // radius of effect
};
